import { describe, expect, it } from 'vitest'
import { createGame, getCell, getGroup, parseBoard, play } from '../../engine'
import { AGREED_DEAD, DEAD_CAPTURE, ENDGAME_LESSONS, ENDING_ROWS, SCORING_ROWS, TERRITORY_QUESTIONS } from '../../content/endgame'
import { answerTerritory, answerWinner, confirmEnding, countHint, emptyRegion, endgameView, endingDemo, endingTurn, lessonScore, selectEndgame, startEndgame, submitCount } from './endgameRunner'
import { answerSequence, sequenceScene, sequenceStep, sequenceView, startRuleSequence } from './ruleSequence'

describe('落子顺序的两种棋形', () => {
  it('一眼先提 14 颗黑子，白棋从零气变成四气，观察不改动起始局面', () => {
    const run = startRuleSequence()
    const initial = sequenceView(run)
    const placed = sequenceView(sequenceStep(run, 1))
    expect(getGroup(placed.board, initial.scene.point)?.liberties).toHaveLength(0)
    const captured = sequenceView(sequenceStep(run, 2))
    expect(captured.inspection.captured).toHaveLength(14)
    expect(getGroup(captured.board, initial.scene.point)?.liberties).toHaveLength(4)
    expect(sequenceView(sequenceStep(run, 3)).legal).toBe(true)
    expect(getCell(initial.board, initial.scene.point)).toBeNull()
    expect(initial.game.history).toEqual([])
  })
  it('两眼不能提黑棋，最后拒绝白子并恢复原图；浏览不会自动判定学会', () => {
    const run = sequenceScene(startRuleSequence(), 1)
    const view = sequenceView(sequenceStep(run, 3))
    expect(view.inspection.result).toEqual({ ok: false, reason: 'suicide' })
    expect(view.inspection.captured).toEqual([])
    expect(view.board).toEqual(sequenceView(run).board)
    expect(run.solved).toEqual([])
    expect(answerSequence(run, true).solved).toEqual([])
    const final = sequenceStep(run, 3)
    expect(answerSequence(final, false).solved).toEqual([])
    expect(answerSequence(final, true).solved).toEqual([1])
  })
})

describe('围地与终局教学', () => {
  it('教学终局的实子、空点、中立点与贴目相符', () => {
    const run = startEndgame(ENDGAME_LESSONS[1])
    const result = lessonScore(run)
    expect([result.blackStones.length, result.blackEmpty.length, result.whiteStones.length, result.whiteEmpty.length]).toEqual([28, 8, 27, 8])
    expect(result.score).toMatchObject({ black: 36, white: 35, komi: 7.5, winner: 'white', margin: 6.5 })
    expect(result.score.ownership.filter((color) => color === null)).toHaveLength(10)
    for (const point of [...result.blackStones, ...result.whiteStones]) expect(getGroup(run.game.board, point)!.liberties.length).toBeGreaterThanOrEqual(2)
    expect(emptyRegion(run.game.board, { x: -1, y: 1 })).toEqual([])
  })
  it('必须先选空区再回答；答错不推进，三种归属都必须完成', () => {
    let run = startEndgame(ENDGAME_LESSONS[0])
    expect(answerTerritory(run, 'black')).toBe(run)
    expect(selectEndgame(run, { x: 0, y: 0 }).picked).toBe(false)
    run = selectEndgame(run, TERRITORY_QUESTIONS[0].point)
    expect(answerTerritory(run, 'white').step).toBe(0)
    for (const question of TERRITORY_QUESTIONS) {
      run = answerTerritory(selectEndgame(run, question.point), question.expected)
    }
    expect(run.done).toBe(true)
    expect(run.game.history).toEqual([])
  })
  it('四类分别核对，不接受空答案或错误数字；提示完成单独标识', () => {
    let run = startEndgame(ENDGAME_LESSONS[1])
    expect(submitCount(run).step).toBe(0)
    expect(submitCount({ ...run, input: '81' }).step).toBe(0)
    run = countHint(run)
    expect(run.assisted).toBe(true)
    for (const input of ['28', '8', '27', '8']) run = submitCount({ ...run, input })
    expect(run.done).toBe(true)
    expect(run.step).toBe(4)
  })
  it('先算白方贴目后分数，再比较胜方，棋盘不会增加棋子', () => {
    const initial = startEndgame(ENDGAME_LESSONS[2])
    expect(answerWinner(initial, 'white')).toBe(initial)
    expect(submitCount({ ...initial, input: '35' }).step).toBe(0)
    const calculated = submitCount({ ...initial, input: '42.5' })
    expect(calculated.done).toBe(false)
    expect(answerWinner(calculated, 'black').done).toBe(false)
    const complete = answerWinner(calculated, 'white')
    expect(complete.done).toBe(true)
    expect(complete.game).toBe(initial.game)
  })
  it('这颗约定死子可以被提，自己填气也逃不出去；其余盘面保持不变', () => {
    const board = parseBoard(ENDING_ROWS)
    expect(getGroup(board, AGREED_DEAD)?.liberties).toEqual([DEAD_CAPTURE])
    expect(play(createGame({ board, toPlay: 'white' }), DEAD_CAPTURE)).toEqual({ ok: false, reason: 'suicide' })
    const capture = play(createGame({ board }), DEAD_CAPTURE)
    expect(capture.ok).toBe(true)
    if (capture.ok) expect(capture.state.history[0]).toMatchObject({ captured: [AGREED_DEAD] })
    const run = { ...startEndgame(ENDGAME_LESSONS[3]), dead: [AGREED_DEAD] }
    expect(lessonScore(run).cleared).toEqual(parseBoard(SCORING_ROWS))
  })
  it('双方必须连续停手；中间落子使计数清零，未确认死子不能结束', () => {
    let run = startEndgame(ENDGAME_LESSONS[3])
    expect(confirmEnding(run)).toBe(run)
    expect(selectEndgame(run, AGREED_DEAD)).toBe(run)
    expect(endingTurn(run, 'white-pass')).toBe(run)
    run = endingTurn(run, 'black-pass')
    expect(run.game.consecutivePasses).toBe(1)
    run = endingTurn(run, 'white-play')
    expect(run.game.consecutivePasses).toBe(0)
    expect(run.game.phase).toBe('playing')
    run = endingTurn(endingTurn(run, 'black-pass'), 'white-pass')
    expect(run.game.phase).toBe('scoring')
    expect(confirmEnding(run).done).toBe(false)
    expect(selectEndgame(run, { x: 0, y: 0 }).dead).toEqual([])
    run = selectEndgame(run, AGREED_DEAD)
    expect(selectEndgame(run, AGREED_DEAD).dead).toEqual([])
    run = confirmEnding(run)
    expect(run.done).toBe(true)
    expect(lessonScore(run).score).toMatchObject({ black: 36, white: 36, margin: 7.5 })
  })
  it('提子演示不更改停手或死子，结束计分不重复加提子分', () => {
    let run = startEndgame(ENDGAME_LESSONS[3])
    run = endingTurn(endingTurn(run, 'black-pass'), 'white-pass')
    const demo = endingDemo(run)
    expect(demo.message).toBeNull()
    expect(getCell(endgameView(demo).board, AGREED_DEAD)).toBeNull()
    expect(demo.game).toBe(run.game)
    expect(confirmEnding(demo)).toBe(demo)
    expect(selectEndgame(demo, AGREED_DEAD)).toBe(demo)
    run = confirmEnding(selectEndgame(endingDemo(demo), AGREED_DEAD))
    expect(lessonScore(run).score).toMatchObject({ black: 36, white: 35, margin: 6.5 })
    expect(run.game.history.map((move) => move.kind)).toEqual(['pass', 'pass'])
  })
})
